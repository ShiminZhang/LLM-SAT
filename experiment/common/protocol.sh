#!/usr/bin/env bash
# Shared runtime protocol for the OpenEvolve, ShinkaEvolve, and LLM-SAT
# comparison runners. Callers may override COMPARISON_* before sourcing this
# file; tool-specific variables remain overridable for standalone debugging.

COMPARISON_MODEL="${COMPARISON_MODEL:-gpt-5.6-luna}"
COMPARISON_REASONING_EFFORT="${COMPARISON_REASONING_EFFORT:-medium}"
COMPARISON_TIMEOUT="${COMPARISON_TIMEOUT:-1200}"
COMPARISON_PAR2_PENALTY="${COMPARISON_PAR2_PENALTY:-2400}"
COMPARISON_JOB_WALLTIME="${COMPARISON_JOB_WALLTIME:-10:00:00}"
COMPARISON_JOB_MEMORY="${COMPARISON_JOB_MEMORY:-32G}"
COMPARISON_JOB_CPUS="${COMPARISON_JOB_CPUS:-8}"
COMPARISON_CPU_CONSTRAINT="${COMPARISON_CPU_CONSTRAINT:-${CPU_CONSTRAINT:-genoa}}"
COMPARISON_MAX_CANDIDATE_JOBS="${COMPARISON_MAX_CANDIDATE_JOBS:-4}"
COMPARISON_KEEP_PROOFS="${COMPARISON_KEEP_PROOFS:-0}"

validate_comparison_protocol() {
  local name value
  for name in \
    COMPARISON_TIMEOUT COMPARISON_JOB_CPUS COMPARISON_MAX_CANDIDATE_JOBS; do
    value="${!name}"
    if ! [[ "$value" =~ ^[1-9][0-9]*$ ]]; then
      echo "$name must be a positive integer (got: $value)" >&2
      return 2
    fi
  done
  if ! [[ "$COMPARISON_PAR2_PENALTY" =~ ^[0-9]+([.][0-9]+)?$ ]]; then
    echo "COMPARISON_PAR2_PENALTY must be a non-negative number" >&2
    return 2
  fi
  if [ "$COMPARISON_KEEP_PROOFS" != "0" ] && [ "$COMPARISON_KEEP_PROOFS" != "1" ]; then
    echo "COMPARISON_KEEP_PROOFS must be 0 or 1" >&2
    return 2
  fi
}

export_comparison_protocol() {
  validate_comparison_protocol
  export COMPARISON_MODEL COMPARISON_REASONING_EFFORT
  export OPENAI_REASONING_EFFORT="${OPENAI_REASONING_EFFORT:-$COMPARISON_REASONING_EFFORT}"
  export OE_TIMEOUT="${OE_TIMEOUT:-$COMPARISON_TIMEOUT}"
  export OE_PAR2_PENALTY="${OE_PAR2_PENALTY:-$COMPARISON_PAR2_PENALTY}"
  export OE_WALL_TIME="${OE_WALL_TIME:-$COMPARISON_JOB_WALLTIME}"
  export OE_SLURM_MEMORY="${OE_SLURM_MEMORY:-$COMPARISON_JOB_MEMORY}"
  export OE_SLURM_CPUS="${OE_SLURM_CPUS:-$COMPARISON_JOB_CPUS}"
  export OE_SLURM_CONSTRAINT="${OE_SLURM_CONSTRAINT:-$COMPARISON_CPU_CONSTRAINT}"
  export OE_KEEP_PROOFS="${OE_KEEP_PROOFS:-$COMPARISON_KEEP_PROOFS}"

  export LLMSAT_TIMEOUT="${LLMSAT_TIMEOUT:-$COMPARISON_TIMEOUT}"
  export LLMSAT_PAR2_PENALTY="${LLMSAT_PAR2_PENALTY:-$COMPARISON_PAR2_PENALTY}"
  export LLMSAT_WALL_TIME="${LLMSAT_WALL_TIME:-$COMPARISON_JOB_WALLTIME}"
  export LLMSAT_SLURM_MEMORY="${LLMSAT_SLURM_MEMORY:-$COMPARISON_JOB_MEMORY}"
  export LLMSAT_SLURM_CPUS="${LLMSAT_SLURM_CPUS:-$COMPARISON_JOB_CPUS}"
  export LLMSAT_SLURM_CONSTRAINT="${LLMSAT_SLURM_CONSTRAINT:-$COMPARISON_CPU_CONSTRAINT}"
  export LLMSAT_MAX_CANDIDATE_JOBS="${LLMSAT_MAX_CANDIDATE_JOBS:-$COMPARISON_MAX_CANDIDATE_JOBS}"
  export LLMSAT_KEEP_PROOFS="${LLMSAT_KEEP_PROOFS:-$COMPARISON_KEEP_PROOFS}"

  export SHINKA_MODEL="${SHINKA_MODEL:-$COMPARISON_MODEL}"
  export SHINKA_REASONING_EFFORT="${SHINKA_REASONING_EFFORT:-$COMPARISON_REASONING_EFFORT}"
  export SHINKA_MAX_EVALUATIONS="${SHINKA_MAX_EVALUATIONS:-$COMPARISON_MAX_CANDIDATE_JOBS}"
}
